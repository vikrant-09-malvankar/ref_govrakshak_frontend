/**
 * Compiled phrase map: lower-cased English -> Marathi.
 * Sorted by key length DESC at call sites for longest-prefix matching.
 */
const phraseEntries = Object.entries(PHRASES).sort(
  (a, b) => b[0].length - a[0].length,
);

const phraseMap = new Map<string, string>(
  phraseEntries.map(([k, v]) => [k.toLowerCase(), v]),
);

const wordMap = new Map<string, string>(
  Object.entries(WORDS).map(([k, v]) => [k.toLowerCase(), v]),
);

// Markers that may trail UI strings: ":", "*", "?", "!", "...", ",", " *"
// (Comma is treated as a trailing marker so dashboard text like
//  "Welcome back, {name}" — which renders as the text node "Welcome back, "
//  — still hits the "welcome back" phrase entry.)
const TRAILING_MARKERS = /(\s*[*:?!,]+|\s*\.{3,}|\s*…)\s*$/;
const LEADING_MARKERS = /^\s*[*:•▸▶➤]\s*/;

/**
 * Translate a UI string to Marathi. Returns the original on no-match.
 * Preserves leading/trailing whitespace and trailing markers (e.g. ":", "*").
 */
export function translateToMarathi(text: string): string {
  if (!text) return text;
  const original = text;

  // Preserve leading and trailing whitespace exactly.
  const leadingWs = original.match(/^\s*/)?.[0] ?? '';
  const trailingWs = original.match(/\s*$/)?.[0] ?? '';
  const normalized = original.slice(leadingWs.length, original.length - trailingWs.length);
  if (!normalized) return original;

  // Strip leading/trailing UI markers (preserve them in output).
  let core = normalized;
  let leadingMark = '';
  let trailingMark = '';
  const lm = core.match(LEADING_MARKERS);
  if (lm) {
    leadingMark = lm[0];
    core = core.slice(leadingMark.length);
  }
  const tm = core.match(TRAILING_MARKERS);
  if (tm) {
    trailingMark = tm[0];
    core = core.slice(0, core.length - trailingMark.length);
  }

  if (!core) return original;

  const key = core.toLowerCase();
  const phrase = phraseMap.get(key);
  if (phrase !== undefined) {
    return leadingWs + leadingMark + phrase + trailingMark + trailingWs;
  }

  // Try without leading articles
  const articleStripped = key.replace(/^(a|an|the)\s+/, '');
  if (articleStripped !== key) {
    const p2 = phraseMap.get(articleStripped);
    if (p2 !== undefined) {
      return leadingWs + leadingMark + p2 + trailingMark + trailingWs;
    }
  }

  if (!/[A-Za-z]/.test(core)) return original;
  // Skip data-shaped content (pure numbers/IDs/dates/emails).
  if (/^[0-9\s\-:./,]+$/.test(core)) return original;
  if (/@/.test(core) && /\.[a-z]{2,}/i.test(core)) return original;
  if (/^\d{4}-\d{2}-\d{2}/.test(core)) return original;

  let anyTranslated = false;
  const translated = core.replace(/([A-Za-z][A-Za-z'-]*)/g, (match: string) => {
    const lower = match.toLowerCase();
    const w = wordMap.get(lower);
    if (w === undefined) return match;
    anyTranslated = true;
    return w;
  });

  if (!anyTranslated) return original;

  const cleaned = translated.replace(/\s{2,}/g, ' ').trim();
  return leadingWs + leadingMark + cleaned + trailingMark + trailingWs;
}

/** True if the text has any English letters worth attempting to translate. */
export function isTranslatable(text: string): boolean {
  if (!text) return false;
  const trimmed = text.trim();
  if (trimmed.length < 2) return false;
  if (!/[A-Za-z]/.test(trimmed)) return false;
  return true;
}
